WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF
SET SQLBLANKLINES ON

CREATE TABLE F1_EVENT (
    EVENT_KEY VARCHAR2(255 CHAR) NOT NULL,
    DISPLAY_NAME VARCHAR2(300 CHAR) NOT NULL,
    EVENT_START_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    EVENT_END_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    CREATED_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    BULK_PROFILE VARCHAR2(100 CHAR) NOT NULL,
    NAMESPACE VARCHAR2(2000 CHAR) NOT NULL,
    SOURCE_SYSTEM VARCHAR2(64 CHAR) NOT NULL,
    SOURCE_TENANT VARCHAR2(128 CHAR) NOT NULL,
    SOURCE_ENTITY VARCHAR2(128 CHAR) NOT NULL,
    SOURCE_KEY VARCHAR2(255 CHAR) NOT NULL,
    SOURCE_UPDATED_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    INGESTED_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    PUBLICATION_KEY VARCHAR2(255 CHAR) NOT NULL,
    SCHEMA_VERSION VARCHAR2(32 CHAR) NOT NULL,
    RECORD_STATE VARCHAR2(64 CHAR) NOT NULL,
    CONSTRAINT PK_F1_EVENT PRIMARY KEY (EVENT_KEY),
    CONSTRAINT UQ_F1_EVENT_SOURCE UNIQUE (SOURCE_SYSTEM, SOURCE_TENANT, SOURCE_ENTITY, SOURCE_KEY),
    CONSTRAINT CK_F1_EVENT_DATES CHECK (EVENT_START_AT_UTC < EVENT_END_AT_UTC)
);

CREATE TABLE F1_ZONE (
    ZONE_KEY VARCHAR2(255 CHAR) NOT NULL,
    EVENT_KEY VARCHAR2(255 CHAR) NOT NULL,
    DISPLAY_NAME VARCHAR2(300 CHAR) NOT NULL,
    CAPACITY_UNIT VARCHAR2(32 CHAR) NOT NULL,
    CAPACITY_PROFILE VARCHAR2(64 CHAR) NOT NULL,
    CAPACITY NUMBER(12, 0) NOT NULL,
    SOURCE_SYSTEM VARCHAR2(64 CHAR) NOT NULL,
    SOURCE_TENANT VARCHAR2(128 CHAR) NOT NULL,
    SOURCE_ENTITY VARCHAR2(128 CHAR) NOT NULL,
    SOURCE_KEY VARCHAR2(255 CHAR) NOT NULL,
    SOURCE_UPDATED_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    INGESTED_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    PUBLICATION_KEY VARCHAR2(255 CHAR) NOT NULL,
    SCHEMA_VERSION VARCHAR2(32 CHAR) NOT NULL,
    RECORD_STATE VARCHAR2(64 CHAR) NOT NULL,
    CONSTRAINT PK_F1_ZONE PRIMARY KEY (ZONE_KEY),
    CONSTRAINT UQ_F1_ZONE_SOURCE UNIQUE (SOURCE_SYSTEM, SOURCE_TENANT, SOURCE_ENTITY, SOURCE_KEY),
    CONSTRAINT CK_F1_ZONE_CAPACITY CHECK (CAPACITY >= 0),
    CONSTRAINT FK_F1_ZONE_EVENT FOREIGN KEY (EVENT_KEY) REFERENCES F1_EVENT (EVENT_KEY)
);

CREATE TABLE F1_PRODUCT (
    PRODUCT_KEY VARCHAR2(255 CHAR) NOT NULL,
    EVENT_KEY VARCHAR2(255 CHAR) NOT NULL,
    DISPLAY_NAME VARCHAR2(300 CHAR) NOT NULL,
    AVAILABILITY VARCHAR2(128 CHAR) NOT NULL,
    PRODUCT_CODE VARCHAR2(64 CHAR) NOT NULL,
    SALE_FROM_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    SALE_TO_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    ACCESS_FROM_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    ACCESS_TO_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    CAPACITY_PER_UNIT_JSON VARCHAR2(2000 CHAR) NOT NULL,
    SOURCE_SYSTEM VARCHAR2(64 CHAR) NOT NULL,
    SOURCE_TENANT VARCHAR2(128 CHAR) NOT NULL,
    SOURCE_ENTITY VARCHAR2(128 CHAR) NOT NULL,
    SOURCE_KEY VARCHAR2(255 CHAR) NOT NULL,
    SOURCE_UPDATED_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    INGESTED_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    PUBLICATION_KEY VARCHAR2(255 CHAR) NOT NULL,
    SCHEMA_VERSION VARCHAR2(32 CHAR) NOT NULL,
    RECORD_STATE VARCHAR2(64 CHAR) NOT NULL,
    CONSTRAINT PK_F1_PRODUCT PRIMARY KEY (PRODUCT_KEY),
    CONSTRAINT UQ_F1_PRODUCT_SOURCE UNIQUE (SOURCE_SYSTEM, SOURCE_TENANT, SOURCE_ENTITY, SOURCE_KEY),
    CONSTRAINT UQ_F1_PRODUCT_EVENT UNIQUE (EVENT_KEY, PRODUCT_KEY),
    CONSTRAINT CK_F1_PRODUCT_SALE_DATES CHECK (SALE_FROM_UTC < SALE_TO_UTC),
    CONSTRAINT CK_F1_PRODUCT_ACCESS_DATES CHECK (ACCESS_FROM_UTC < ACCESS_TO_UTC),
    CONSTRAINT FK_F1_PRODUCT_EVENT FOREIGN KEY (EVENT_KEY) REFERENCES F1_EVENT (EVENT_KEY)
);

CREATE TABLE F1_PRICE (
    PRICE_KEY VARCHAR2(255 CHAR) NOT NULL,
    EVENT_KEY VARCHAR2(255 CHAR) NOT NULL,
    PRODUCT_KEY VARCHAR2(255 CHAR) NOT NULL,
    AMOUNT_MINOR NUMBER(18, 0) NOT NULL,
    CURRENCY CHAR(3 CHAR) NOT NULL,
    TAX_TREATMENT VARCHAR2(32 CHAR) NOT NULL,
    EFFECTIVE_FROM_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    EFFECTIVE_TO_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    SOURCE_SYSTEM VARCHAR2(64 CHAR) NOT NULL,
    SOURCE_TENANT VARCHAR2(128 CHAR) NOT NULL,
    SOURCE_ENTITY VARCHAR2(128 CHAR) NOT NULL,
    SOURCE_KEY VARCHAR2(255 CHAR) NOT NULL,
    SOURCE_UPDATED_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    INGESTED_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    PUBLICATION_KEY VARCHAR2(255 CHAR) NOT NULL,
    SCHEMA_VERSION VARCHAR2(32 CHAR) NOT NULL,
    RECORD_STATE VARCHAR2(64 CHAR) NOT NULL,
    CONSTRAINT PK_F1_PRICE PRIMARY KEY (PRICE_KEY),
    CONSTRAINT UQ_F1_PRICE_SOURCE UNIQUE (SOURCE_SYSTEM, SOURCE_TENANT, SOURCE_ENTITY, SOURCE_KEY),
    CONSTRAINT CK_F1_PRICE_AMOUNT CHECK (AMOUNT_MINOR >= 0),
    CONSTRAINT CK_F1_PRICE_CURRENCY CHECK (CURRENCY = UPPER(CURRENCY)),
    CONSTRAINT CK_F1_PRICE_DATES CHECK (EFFECTIVE_FROM_UTC < EFFECTIVE_TO_UTC),
    CONSTRAINT FK_F1_PRICE_PRODUCT FOREIGN KEY (EVENT_KEY, PRODUCT_KEY)
        REFERENCES F1_PRODUCT (EVENT_KEY, PRODUCT_KEY)
);

CREATE TABLE F1_BUNDLE_COMPONENT (
    BUNDLE_COMPONENT_KEY VARCHAR2(255 CHAR) NOT NULL,
    BUNDLE_PRODUCT_KEY VARCHAR2(255 CHAR) NOT NULL,
    COMPONENT_PRODUCT_KEY VARCHAR2(255 CHAR) NOT NULL,
    QUANTITY NUMBER(10, 0) NOT NULL,
    SOURCE_SYSTEM VARCHAR2(64 CHAR) NOT NULL,
    SOURCE_TENANT VARCHAR2(128 CHAR) NOT NULL,
    SOURCE_ENTITY VARCHAR2(128 CHAR) NOT NULL,
    SOURCE_KEY VARCHAR2(255 CHAR) NOT NULL,
    SOURCE_UPDATED_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    INGESTED_AT_UTC TIMESTAMP(6) WITH LOCAL TIME ZONE NOT NULL,
    PUBLICATION_KEY VARCHAR2(255 CHAR) NOT NULL,
    SCHEMA_VERSION VARCHAR2(32 CHAR) NOT NULL,
    RECORD_STATE VARCHAR2(64 CHAR) NOT NULL,
    CONSTRAINT PK_F1_BUNDLE_COMPONENT PRIMARY KEY (BUNDLE_COMPONENT_KEY),
    CONSTRAINT UQ_F1_BUNDLE_SOURCE UNIQUE (SOURCE_SYSTEM, SOURCE_TENANT, SOURCE_ENTITY, SOURCE_KEY),
    CONSTRAINT CK_F1_BUNDLE_QUANTITY CHECK (QUANTITY > 0),
    CONSTRAINT CK_F1_BUNDLE_PRODUCTS CHECK (BUNDLE_PRODUCT_KEY <> COMPONENT_PRODUCT_KEY),
    CONSTRAINT FK_F1_BUNDLE_PARENT FOREIGN KEY (BUNDLE_PRODUCT_KEY) REFERENCES F1_PRODUCT (PRODUCT_KEY),
    CONSTRAINT FK_F1_BUNDLE_COMPONENT FOREIGN KEY (COMPONENT_PRODUCT_KEY) REFERENCES F1_PRODUCT (PRODUCT_KEY)
);

COMMIT;
